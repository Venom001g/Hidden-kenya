import type { Tables } from "@/lib/database.types";
import { fromMinorUnits } from "@/lib/format";
import type { ListingInput } from "@/lib/validation/listing";

export const EMPTY_LISTING: ListingInput = {
  title: "",
  summary: "",
  description: "",
  categoryId: "",
  countyCode: 0,
  destinationId: "",
  pricingModel: "per_person",
  price: "",
  currency: "KES",
  durationHours: 3,
  durationMinutes: 0,
  minParticipants: 1,
  maxParticipants: 8,
  included: "",
  excluded: "",
  languages: "English, Kiswahili",
  tags: "",
  accessibilityFeatures: [],
  accessibilityNotes: "",
  meetingPointName: "",
  meetingPointInstructions: "",
  meetingLatitude: "",
  meetingLongitude: "",
  bookingMode: "instant",
  leadTimeHours: 24,
  maxAdvanceDays: 365,
  cancellationPolicy: "moderate",
};

export function listingToInput(l: Tables<"experiences">): ListingInput {
  return {
    title: l.title,
    summary: l.summary,
    description: l.description,
    categoryId: l.category_id,
    countyCode: l.county_code,
    destinationId: l.destination_id ?? "",
    pricingModel: l.pricing_model,
    price: fromMinorUnits(l.price_minor, l.currency),
    currency: l.currency as "KES" | "USD",
    durationHours: Math.floor(l.duration_minutes / 60),
    durationMinutes: l.duration_minutes % 60,
    minParticipants: l.min_participants,
    maxParticipants: l.max_participants,
    included: l.included.join("\n"),
    excluded: l.excluded.join("\n"),
    languages: l.languages.join(", "),
    tags: l.tags.join(", "),
    accessibilityFeatures: l.accessibility_features as ListingInput["accessibilityFeatures"],
    accessibilityNotes: l.accessibility_notes,
    meetingPointName: l.meeting_point_name,
    meetingPointInstructions: l.meeting_point_instructions,
    meetingLatitude: l.meeting_latitude === null ? "" : String(l.meeting_latitude),
    meetingLongitude: l.meeting_longitude === null ? "" : String(l.meeting_longitude),
    bookingMode: l.booking_mode,
    leadTimeHours: l.lead_time_hours,
    maxAdvanceDays: l.max_advance_days,
    cancellationPolicy: l.cancellation_policy,
  };
}
