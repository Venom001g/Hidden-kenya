/**
 * Generates src/lib/database.types.ts in the same shape as `supabase gen types typescript`,
 * by introspecting a database that has the migrations applied (normally the local test DB).
 *
 *   TEST_DATABASE_URL=postgres://... npm run db:types
 *
 * With a linked Supabase project you can use the official generator instead:
 *   npx supabase gen types typescript --project-id <ref> --schema public > src/lib/database.types.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL ?? process.env.DATABASE_URL;
if (!url) throw new Error("Set TEST_DATABASE_URL (or DATABASE_URL) to a migrated database.");

const client = new pg.Client({ connectionString: url });

type Col = {
  table_name: string;
  column_name: string;
  is_nullable: "YES" | "NO";
  column_default: string | null;
  is_generated: string;
  is_identity: string;
  udt_name: string;
  data_type: string;
  ordinal_position: number;
};

const scalar = (udt: string, enums: Set<string>): string => {
  if (udt.startsWith("_")) return `${scalar(udt.slice(1), enums)}[]`;
  if (enums.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  switch (udt) {
    case "int2":
    case "int4":
    case "int8":
    case "float4":
    case "float8":
    case "numeric":
      return "number";
    case "bool":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    case "void":
      return "undefined";
    default:
      return "string";
  }
};

async function main() {
  await client.connect();

  const enumRows = (
    await client.query<{ name: string; values: string[] }>(`
      select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder)::text[] as values
      from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
      where n.nspname = 'public' group by t.typname order by t.typname`)
  ).rows;
  const enums = new Set(enumRows.map((e) => e.name));

  const relations = (
    await client.query<{ name: string; kind: string }>(`
      select c.relname as name, c.relkind as kind from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind in ('r', 'v') order by c.relname`)
  ).rows;

  const cols = (
    await client.query<Col>(`
      select table_name, column_name, is_nullable, column_default, is_generated, is_identity, udt_name, data_type, ordinal_position
      from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`)
  ).rows;

  const fks = (
    await client.query<{
      name: string;
      table_name: string;
      columns: string[];
      ref_table: string;
      ref_columns: string[];
      one_to_one: boolean;
    }>(`
      select con.conname as name, rel.relname as table_name,
             array(select a.attname from unnest(con.conkey) with ordinality as k(num, ord) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.num order by k.ord)::text[] as columns,
             frel.relname as ref_table,
             array(select a.attname from unnest(con.confkey) with ordinality as k(num, ord) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.num order by k.ord)::text[] as ref_columns,
             exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('p','u')
                     and u.conkey::int[] @> con.conkey::int[] and u.conkey::int[] <@ con.conkey::int[]) as one_to_one
      from pg_constraint con
      join pg_class rel on rel.oid = con.conrelid join pg_namespace n on n.oid = rel.relnamespace
      join pg_class frel on frel.oid = con.confrelid join pg_namespace fn on fn.oid = frel.relnamespace
      where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
      order by con.conname`)
  ).rows;

  const fns = (
    await client.query<{
      name: string;
      arg_names: string[] | null;
      arg_types: string[];
      arg_modes: string[] | null;
      n_defaults: number;
      ret_type: string;
      ret_set: boolean;
    }>(`
      select p.proname as name, p.proargnames::text[] as arg_names,
             array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as o(oid, ord) join pg_type t on t.oid = o.oid order by o.ord)::text[] as arg_types,
             p.proargmodes::text[] as arg_modes, p.pronargdefaults as n_defaults,
             rt.typname as ret_type, p.proretset as ret_set
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
      where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
      order by p.proname`)
  ).rows;

  const ind = (n: number) => "  ".repeat(n);
  const out: string[] = [];
  out.push("// Generated by scripts/gen-db-types.ts — do not edit by hand.");
  out.push(
    "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];",
    "",
    "export type Database = {",
    `${ind(1)}public: {`,
  );

  const emitRel = (kind: "r" | "v") => {
    for (const rel of relations.filter((r) => r.kind === kind)) {
      const rc = cols.filter((c) => c.table_name === rel.name);
      out.push(`${ind(3)}${rel.name}: {`);
      out.push(`${ind(4)}Row: {`);
      for (const c of rc) {
        const t = scalar(c.udt_name, enums);
        out.push(`${ind(5)}${c.column_name}: ${t}${c.is_nullable === "YES" || kind === "v" ? " | null" : ""};`);
      }
      out.push(`${ind(4)}};`);
      if (kind === "r") {
        for (const mode of ["Insert", "Update"] as const) {
          out.push(`${ind(4)}${mode}: {`);
          for (const c of rc) {
            const t = scalar(c.udt_name, enums);
            const nullable = c.is_nullable === "YES";
            if (c.is_generated === "ALWAYS" || c.is_identity === "YES") {
              out.push(`${ind(5)}${c.column_name}?: never;`);
              continue;
            }
            const optional = mode === "Update" || nullable || c.column_default !== null;
            out.push(`${ind(5)}${c.column_name}${optional ? "?" : ""}: ${t}${nullable ? " | null" : ""};`);
          }
          out.push(`${ind(4)}};`);
        }
      }
      out.push(`${ind(4)}Relationships: [`);
      for (const fk of fks.filter((f) => f.table_name === rel.name)) {
        out.push(
          `${ind(5)}{ foreignKeyName: "${fk.name}"; columns: ${JSON.stringify(fk.columns)}; isOneToOne: ${fk.one_to_one}; referencedRelation: "${fk.ref_table}"; referencedColumns: ${JSON.stringify(fk.ref_columns)} },`,
        );
      }
      out.push(`${ind(4)}];`);
      out.push(`${ind(3)}};`);
    }
  };

  out.push(`${ind(2)}Tables: {`);
  emitRel("r");
  out.push(`${ind(2)}};`);
  out.push(`${ind(2)}Views: {`);
  emitRel("v");
  out.push(`${ind(2)}};`);

  out.push(`${ind(2)}Functions: {`);
  for (const f of fns) {
    const names = f.arg_names ?? [];
    const modes = f.arg_modes ?? f.arg_types.map(() => "i");
    const inputs: { name: string; type: string }[] = [];
    const outputs: { name: string; type: string }[] = [];
    f.arg_types.forEach((t, i) => {
      const entry = { name: names[i] ?? `arg${i}`, type: scalar(t, enums) };
      if (modes[i] === "i" || modes[i] === "b") inputs.push(entry);
      if (modes[i] === "o" || modes[i] === "t" || modes[i] === "b") outputs.push(entry);
    });
    const firstDefault = inputs.length - f.n_defaults;
    const args = inputs.length
      ? `{ ${inputs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${a.type}${i >= firstDefault ? " | null" : ""}`).join("; ")} }`
      : "Record<PropertyKey, never>";
    let ret: string;
    if (outputs.length) ret = `{ ${outputs.map((o) => `${o.name}: ${o.type}`).join("; ")} }[]`;
    else {
      ret = scalar(f.ret_type, enums);
      if (f.ret_set) ret = `${ret}[]`;
    }
    out.push(`${ind(3)}${f.name}: { Args: ${args}; Returns: ${ret} };`);
  }
  out.push(`${ind(2)}};`);

  out.push(`${ind(2)}Enums: {`);
  for (const e of enumRows) out.push(`${ind(3)}${e.name}: ${e.values.map((v) => JSON.stringify(v)).join(" | ")};`);
  out.push(`${ind(2)}};`);
  out.push(`${ind(2)}CompositeTypes: { [_ in never]: never };`);
  out.push(`${ind(1)}};`, "};", "");

  out.push(
    'type PublicSchema = Database["public"];',
    'export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];',
    'export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];',
    'export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];',
    'export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];',
    "",
  );

  const target = path.resolve(__dirname, "../src/lib/database.types.ts");
  writeFileSync(target, out.join("\n"));
  console.log(`Wrote ${target}`);
  await client.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
